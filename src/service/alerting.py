"""
ROE Gate Alerting — Slack and Webhook Notifications

Sends real-time alerts when the Gate makes enforcement decisions.
Supports Slack webhooks, generic HTTP webhooks, and configurable
alert thresholds.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import logging
import threading
import urllib.request
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from enum import Enum
from typing import Any


logger = logging.getLogger("roe_gate.alerting")


# ---------------------------------------------------------------------------
# Data types
# ---------------------------------------------------------------------------

class AlertLevel(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"

    def __ge__(self, other: AlertLevel) -> bool:
        order = {AlertLevel.INFO: 0, AlertLevel.WARNING: 1, AlertLevel.CRITICAL: 2}
        return order[self] >= order[other]

    def __gt__(self, other: AlertLevel) -> bool:
        order = {AlertLevel.INFO: 0, AlertLevel.WARNING: 1, AlertLevel.CRITICAL: 2}
        return order[self] > order[other]

    def __lt__(self, other: AlertLevel) -> bool:
        order = {AlertLevel.INFO: 0, AlertLevel.WARNING: 1, AlertLevel.CRITICAL: 2}
        return order[self] < order[other]

    def __le__(self, other: AlertLevel) -> bool:
        order = {AlertLevel.INFO: 0, AlertLevel.WARNING: 1, AlertLevel.CRITICAL: 2}
        return order[self] <= order[other]


@dataclass
class AlertEvent:
    """A single alert event generated by the Gate."""
    level: AlertLevel
    event_type: str
    summary: str
    details: dict[str, Any] = field(default_factory=dict)
    timestamp: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    def to_dict(self) -> dict[str, Any]:
        return {
            "level": self.level.value,
            "event_type": self.event_type,
            "summary": self.summary,
            "details": self.details,
            "timestamp": self.timestamp,
        }

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":"))


