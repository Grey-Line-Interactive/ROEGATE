_DECISION_LEVEL = {
    "ALLOW": AlertLevel.INFO,
    "DENY": AlertLevel.WARNING,
    "HALT": AlertLevel.CRITICAL,
    "ESCALATE": AlertLevel.WARNING,
}


def gate_result_to_alert(intent: Any, result: Any) -> AlertEvent:
    """Convert a GateResult (and its originating ActionIntent) into an AlertEvent.

    Args:
        intent: An ``ActionIntent`` instance.
        result: A ``GateResult`` instance.

    Returns:
        An ``AlertEvent`` ready to be dispatched.
    """
    decision = result.decision.value if hasattr(result.decision, "value") else str(result.decision)
    level = _DECISION_LEVEL.get(decision, AlertLevel.WARNING)

    summary = f"{decision}: {intent.tool} -> {intent.target.host or 'unknown'}"

    details: dict[str, Any] = {
        "decision": decision,
        "tool": intent.tool,
        "category": intent.category.value if hasattr(intent.category, "value") else str(intent.category),
        "target_host": intent.target.host if hasattr(intent.target, "host") else "",
        "reasoning": result.reasoning,
        "intent_id": intent.intent_id,
    }
    if hasattr(result, "denial_count"):
        details["denial_count"] = result.denial_count

    return AlertEvent(
        level=level,
        event_type=f"gate_{decision.lower()}",
        summary=summary,
        details=details,
    )
